using System.Diagnostics;
using HassHwStats.Core;
using HassHwStats.Mqtt;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;

namespace HassHwStats;

public sealed class Worker(AppOptions options, IReadOnlyList<ISensorSource> sources, MqttPublisher publisher, ILogger<Worker> log) : BackgroundService
{
    protected override async Task ExecuteAsync(CancellationToken ct)
    {
        var active = StartSources(sources, log);
        var interval = TimeSpan.FromMilliseconds(Math.Max(250, options.IntervalMs));
        using var timer = new PeriodicTimer(interval);
        var slow = Stopwatch.StartNew();
        var seen = new Dictionary<string, SensorDefinition>();
        var dashboardPath = Path.Combine(AppContext.BaseDirectory, "dashboard.yaml");

        do
        {
            var sw = Stopwatch.StartNew();
            var values = PollAll(active, log);
            await publisher.PublishReadingsAsync(values, ct);
            if (options.WriteDashboard && values.Any(v => seen.TryAdd(v.Definition.Key, v.Definition)))
                WriteDashboard(dashboardPath, seen.Values, log);
            if (sw.Elapsed > interval && slow.Elapsed > TimeSpan.FromMinutes(5))
            {
                log.LogWarning("Reading sensors took {Ms} ms, longer than the {Interval} ms interval", sw.ElapsedMilliseconds, interval.TotalMilliseconds);
                slow.Restart();
            }
        }
        while (await timer.WaitForNextTickAsync(ct));
    }

    private string? _lastDashboard;

    private void WriteDashboard(string path, IReadOnlyCollection<SensorDefinition> defs, ILogger log)
    {
        try
        {
            var pc = defs.FirstOrDefault(d => d.Device.Id == "pc")?.Device.Name ?? options.NodeName ?? Environment.MachineName;
            var yaml = "# Generated by HassHwStats from the entities this PC publishes. Paste into a dashboard's raw configuration editor.\n"
                       + DashboardWriter.Build(pc, defs);
            if (yaml == _lastDashboard) return;
            File.WriteAllText(path, yaml);
            if (_lastDashboard is null) log.LogInformation("Wrote Home Assistant dashboard to {Path}", path);
            _lastDashboard = yaml;
        }
        catch (Exception ex)
        {
            log.LogWarning("Could not write {Path}: {Message}", path, ex.Message);
        }
    }

    public static List<ISensorSource> StartSources(IEnumerable<ISensorSource> sources, ILogger log)
    {
        var active = new List<ISensorSource>();
        foreach (var s in sources)
        {
            try
            {
                s.Start();
                active.Add(s);
                log.LogInformation("Started source {Source}", s.Name);
            }
            catch (Exception ex)
            {
                log.LogError(ex, "Source {Source} failed to start and is disabled", s.Name);
            }
        }
        return active;
    }

    public static List<SensorValue> PollAll(IEnumerable<ISensorSource> sources, ILogger log)
    {
        var values = new List<SensorValue>(256);
        foreach (var s in sources)
        {
            try
            {
                values.AddRange(s.Poll());
            }
            catch (Exception ex)
            {
                log.LogWarning("Reading {Source} failed: {Message}", s.Name, ex.Message);
            }
        }
        return values;
    }

    public override void Dispose()
    {
        foreach (var s in sources) s.Dispose();
        base.Dispose();
    }
}
